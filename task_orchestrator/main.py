def main():
    parser = argparse.ArgumentParser(description="Task Orchestrator")
    parser.add_argument("user_id", type=str, help="The ID of the user initiating the task.")
    parser.add_argument("task_description", type=str, help="A description of the task to be executed.")
    args = parser.parse_args()

    # Before calling accept_task, ensure environment variables like OPENAI_API_KEY are loaded
    # if this script is the entry point. For simplicity in module structure,
    # we assume .env is loaded by the execution environment or a top-level script.
    # If OPENAI_API_KEY is needed by reasoning_engine and not set, generate_plan will handle it.

    # For testing, explicitly load .env if running this directly and it's the main entry point
    if __name__ == "__main__":
        try:
            from dotenv import load_dotenv
            dotenv_path = os.path.join(project_root, '.env')
            if os.path.exists(dotenv_path):
                load_dotenv(dotenv_path=dotenv_path)
                logging.info(f"Loaded .env file from {dotenv_path}")
            else:
                logging.info(".env file not found, relying on environment-set variables.")
        except ImportError:
            logging.info("python-dotenv not installed. Relying on environment-set variables.")
        except Exception as e:
            logging.error(f"Error loading .env: {e}")


    accept_task(args.user_id, args.task_description)

if __name__ == "__main__":
    main()
