import logging
import argparse
import os
import sys

# Add project root to sys.path to allow importing reasoning_engine
project_root = os.path.abspath(os.path.join(os.path.dirname(__file__), '..'))
if project_root not in sys.path:
    sys.path.insert(0, project_root)

from reasoning_engine import engine as reasoning_engine # Import the reasoning engine

# Configure basic logging
logging.basicConfig(level=logging.INFO, format='%(asctime)s - %(levelname)s - %(message)s')

def accept_task(user_id: str, task_description: str):
    """
    Accepts a user ID and task description, generates a plan using the
    reasoning engine, and logs both.
    """
    logging.info(f"Task received for user_id '{user_id}': {task_description}")

    # Generate plan using the reasoning engine
    plan = reasoning_engine.generate_plan(user_id, task_description)

    if plan:
        logging.info(f"Generated plan for user_id '{user_id}':")
        for i, step in enumerate(plan):
            logging.info(f"  Step {i+1}: {step}")
    else:
        logging.warning(f"No plan generated by the reasoning engine for user_id '{user_id}' and task: {task_description}")
        logging.warning("This could be due to a missing/invalid OPENAI_API_KEY or an issue with the LLM.")


